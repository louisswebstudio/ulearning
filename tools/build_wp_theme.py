"""Build the WordPress theme (wp-theme/utalk) and its upload zip (dist/utalk-theme.zip) from site/.

The static site stays the source of truth: every page's <main> becomes a page template
(front-page.php, page-<slug>.php), the shared navbar/footer become header.php/footer.php,
and every internal link is rewritten to a WordPress URL. The theme creates the matching
pages itself when it is activated (see wp-src/functions.php).

Hand-written PHP and CSS that only exist in WordPress live in tools/wp-src/ and are copied as-is.

Run from the project root:  python tools/build_wp_theme.py
"""
import posixpath
import re
import shutil
import zipfile
from html import unescape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
SRC = ROOT / "tools" / "wp-src"
OUT = ROOT / "wp-theme" / "utalk"
ZIP = ROOT / "dist" / "utalk-theme.zip"

VERSION = "1.11.0"

# static page -> (page path in WordPress, template file). Order = creation order (parents first).
PAGES = [
    ("index.html", "", "front-page.php"),
    ("langues.html", "langues", None),
    ("langues/english.html", "langues/english", None),
    ("langues/francais.html", "langues/francais", None),
    ("langues/deutsch.html", "langues/deutsch", None),
    ("langues/espanol.html", "langues/espanol", None),
    ("langues/italiano.html", "langues/italiano", None),
    ("programmes.html", "programmes", None),
    ("programmes/cours-de-langues.html", "programmes/cours-de-langues", None),
    ("programmes/communication-speaking.html", "programmes/communication-speaking", None),
    ("programmes/cours-intensifs.html", "programmes/cours-intensifs", None),
    ("programmes/cours-individuels.html", "programmes/cours-individuels", None),
    ("preparation.html", "preparation", None),
    ("methode.html", "methode", None),
    ("experience.html", "experience", None),
    ("talklab.html", "talklab", None),
    ("etudiants.html", "etudiants", None),
    ("centre.html", "centre", None),
    ("contact.html", "contact", None),
]
HTML_TO_PATH = {html: path for html, path, _ in PAGES}

PHP_HEADER = "<?php\n/**\n * {what}\n * Generated by tools/build_wp_theme.py from site/{src}. Edit the static page, then rebuild.\n *\n * @package utalk\n */\n\n{body}?>\n"


def php_url(target_path, fragment=""):
    frag = f", '#{fragment}'" if fragment else ""
    return f"<?php echo esc_url( utalk_url( '{target_path}'{frag} ) ); ?>"


def rewrite_links(html, page_rel, keep_hash=True):
    """Turn static hrefs/srcs into PHP. page_rel = this page's path inside site/ (e.g. 'langues/english.html')."""
    base = posixpath.dirname(page_rel)

    def repl(m):
        attr, val = m.group(1), m.group(2)
        if re.match(r"(https?:|tel:|mailto:|data:|<\?php)", val):
            return m.group(0)
        if val.startswith("#"):
            if keep_hash:
                return m.group(0)
            return f'{attr}="{php_url("", val[1:])}"' if val != "#" else f'{attr}="{php_url("")}"'
        path, _, frag = val.partition("#")
        target = posixpath.normpath(posixpath.join(base, path))
        if target.startswith("assets/"):
            return f"{attr}=\"<?php echo esc_url( get_theme_file_uri( '{target}' ) ); ?>\""
        if target in HTML_TO_PATH:
            return f'{attr}="{php_url(HTML_TO_PATH[target], frag)}"'
        raise SystemExit(f"{page_rel}: unknown link target {val!r}")

    return re.sub(r'\b(href|src)="([^"]*)"', repl, html)


def contact_form(html):
    """Static form -> real WordPress form (posted to admin-post.php, see utalk_handle_contact)."""
    html = html.replace(
        '<form class="contact__card" id="contact-form" novalidate>',
        '<form class="contact__card" id="contact-form" method="post" action="<?php echo esc_url( admin_url( \'admin-post.php\' ) ); ?>" novalidate>\n'
        "      <?php utalk_contact_hidden_fields(); ?>",
    )
    html = html.replace('id="cf-error" role="alert" hidden>', 'id="cf-error" role="alert"<?php utalk_contact_hidden( \'error\' ); ?>>')
    html = html.replace('id="cf-success" role="status" hidden>', 'id="cf-success" role="status"<?php utalk_contact_hidden( \'sent\' ); ?>>')
    return html


def nav_current(html):
    """Mark the current page in the navbar from PHP (utalk_current) instead of a static aria-current."""
    html = html.replace(' aria-current="page"', "")

    def repl(m):
        path = m.group(1)
        return f"{m.group(0)}<?php utalk_current( '{path}' ); ?>"

    html = re.sub(r"href=\"<\?php echo esc_url\( utalk_url\( '([a-z/-]*)' \) \); \?>\"", repl, html)
    return html.replace("<?php utalk_current( '' ); ?> class=\"nav__logo\"", ' class="nav__logo"')


def extract(html, start, end):
    i, j = html.index(start), html.index(end) + len(end)
    return html[i:j]


def page_meta(html):
    title = unescape(re.search(r"<title>([^<]*)</title>", html).group(1))
    desc = unescape(re.search(r'<meta name="description" content="([^"]*)"', html).group(1))
    return title, desc


def main_inner(html):
    return html[html.index("<main>") + len("<main>"):html.index("</main>")].strip("\n")


def build():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    # Hand-written theme files + static assets
    shutil.copytree(SRC, OUT, dirs_exist_ok=True)
    shutil.copytree(SITE / "assets", OUT / "assets", dirs_exist_ok=True)
    shutil.copy(SITE / "favicon.ico", OUT / "assets" / "img" / "favicon.ico")

    # Shared navbar + footer, taken from an inner page (links there point at real pages, not "#")
    ref_rel = "contact.html"
    ref = (SITE / ref_rel).read_text(encoding="utf8")
    nav = nav_current(rewrite_links(extract(ref, '<header class="nav">', "</header>"), ref_rel))
    footer = rewrite_links(extract(ref, '<footer class="footer">', "</footer>"), ref_rel).replace(' aria-current="page"', "")
    intro_script = extract(ref, "<script>/* intro", "</script>")
    intro = extract(ref, '<div class="intro" aria-hidden="true">', "</svg>\n    <span class=\"intro__bar\"></span>\n  </div>\n</div>")
    footer = footer.replace("© 2026 UTALK Center.", "© <?php echo esc_html( wp_date( 'Y' ) ); ?> UTALK Center.")

    (OUT / "header.php").write_text(
        "<?php\n/**\n * Site header: <head>, navbar, opening <main>.\n"
        " * Generated by tools/build_wp_theme.py from site/contact.html.\n *\n * @package utalk\n */\n?>\n"
        "<!doctype html>\n<html <?php language_attributes(); ?>>\n<head>\n"
        '<meta charset="<?php bloginfo( \'charset\' ); ?>">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"{intro_script}\n"
        "<?php wp_head(); ?>\n</head>\n<body <?php body_class(); ?>>\n<?php wp_body_open(); ?>\n"
        f"{intro}\n"
        '<a class="skip-link" href="#main">Aller au contenu</a>\n\n'
        f"{nav}\n\n<main id=\"main\">\n",
        encoding="utf8",
    )
    (OUT / "footer.php").write_text(
        "<?php\n/**\n * Site footer: closing </main>, footer, wp_footer().\n"
        " * Generated by tools/build_wp_theme.py from site/contact.html.\n *\n * @package utalk\n */\n?>\n"
        f"</main>\n\n{footer}\n\n<?php wp_footer(); ?>\n</body>\n</html>\n",
        encoding="utf8",
    )

    # One template per page + the page list used on activation
    rows = []
    for html_rel, wp_path, template in PAGES:
        html = (SITE / html_rel).read_text(encoding="utf8")
        title, desc = page_meta(html)
        body = contact_form(rewrite_links(main_inner(html), html_rel, keep_hash=(html_rel == "index.html")))
        slug = wp_path.rsplit("/", 1)[-1]
        template = template or f"page-{slug}.php"
        what = "Front page" if not wp_path else f"Page template for /{wp_path}/"
        (OUT / template).write_text(
            PHP_HEADER.format(what=what, src=html_rel, body="get_header();\n")
            + body + "\n<?php\nget_footer();\n",
            encoding="utf8",
        )
        page_title = "Accueil" if not wp_path else title.split(" · ")[0]
        if html_rel == "centre.html":
            page_title = "UTALK Center"
        rows.append((wp_path, page_title, desc))

    php_rows = "".join(
        f"\t\tarray( '{p}', '{t.replace(chr(39), chr(92) + chr(39))}', '{d.replace(chr(39), chr(92) + chr(39))}' ),\n" for p, t, d in rows
    )
    (OUT / "inc" / "pages.php").write_text(
        PHP_HEADER.format(
            what="The pages this theme ships with: path, title, meta description.",
            src="*.html",
            body="defined( 'ABSPATH' ) || exit;\n\nfunction utalk_pages() {\n\treturn array(\n" + php_rows + "\t);\n}\n",
        ),
        encoding="utf8",
    )

    style = (OUT / "style.css").read_text(encoding="utf8").replace("{{VERSION}}", VERSION)
    (OUT / "style.css").write_text(style, encoding="utf8")
    funcs = (OUT / "functions.php").read_text(encoding="utf8").replace("{{VERSION}}", VERSION)
    (OUT / "functions.php").write_text(funcs, encoding="utf8")

    # Zip with a top-level utalk/ folder, as WordPress expects
    ZIP.parent.mkdir(exist_ok=True)
    if ZIP.exists():
        ZIP.unlink()
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(OUT.rglob("*")):
            if f.is_file() and f.name != ".DS_Store":
                z.write(f, Path("utalk") / f.relative_to(OUT))
    print(f"wrote {OUT.relative_to(ROOT)} ({sum(1 for _ in OUT.rglob('*.php'))} PHP files) and {ZIP.relative_to(ROOT)} ({ZIP.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    build()
